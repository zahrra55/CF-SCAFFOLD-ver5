ACC = {
 "á": r"{\'a}", "é": r"{\'e}", "í": r"{\'i}", "ó": r"{\'o}", "ú": r"{\'u}", "ý": r"{\'y}",
 "Á": r"{\'A}", "É": r"{\'E}", "Í": r"{\'I}", "Ó": r"{\'O}", "Ú": r"{\'U}",
 "à": r"{\`a}", "è": r"{\`e}", "ì": r"{\`i}", "ò": r"{\`o}", "ù": r"{\`u}",
 "ä": r'{\"a}', "ë": r'{\"e}', "ï": r'{\"i}', "ö": r'{\"o}', "ü": r'{\"u}',
 "Ä": r'{\"A}', "Ö": r'{\"O}', "Ü": r'{\"U}',
 "â": r"{\^a}", "ê": r"{\^e}", "î": r"{\^i}", "ô": r"{\^o}", "û": r"{\^u}",
 "ñ": r"{\~n}", "ã": r"{\~a}", "õ": r"{\~o}", "ç": r"{\c{c}}", "ş": r"{\c{s}}",
 "š": r"{\v{s}}", "Š": r"{\v{S}}", "č": r"{\v{c}}", "Č": r"{\v{C}}", "ž": r"{\v{z}}",
 "ř": r"{\v{r}}", "ě": r"{\v{e}}", "ć": r"{\'c}", "ń": r"{\'n}", "ğ": r"{\u{g}}", "ı": r"{\i}", "İ": r"{\.I}", "ő": r"{\H{o}}", "ű": r"{\H{u}}", "ş": r"{\c{s}}",
 "ø": r"{\o}", "å": r"{\aa}", "ß": r"{\ss}", "ł": r"{\l}", "æ": r"{\ae}",
 "–": "--", "‐": "-", "‑": "-", "−": "-", "‒": "-", "—": "---", "’": "'", "‘": "`", "“": "``", "”": "''", "®": "", " ": " ",
}
def tex(v):
    v = str(v)
    out = "".join(ACC.get(ch, ch) for ch in v)
    bad = {ch for ch in out if ord(ch) > 127}
    if bad:
        raise ValueError(f"unmapped non-ASCII {bad} in {v!r}")
    return out
